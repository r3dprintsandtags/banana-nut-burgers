// Default registration form definition (registration-v1).
// IMPORTANT: No business-approved legal forms were present in the workspace.
// This is a safe default template, NOT a liability waiver and NOT legal advice.
// The business (with qualified legal review) must approve/replace this text
// before production use. Bump FORM_VERSION whenever wording changes; every
// submission stores the version + full text snapshot hash it was signed under.

export const FORM_VERSION = "registration-v1";

export const DECLARATION_TITLE = "Customer Information Accuracy Declaration";
export const DECLARATION_TEXT =
  "I certify that the information I have provided in this registration form is true, accurate, complete, and current to the best of my knowledge and belief. I understand that I am responsible for reviewing my answers and notifying Banana Nut Burger of any material changes or corrections.";
export const DECLARATION_CHECKBOX = "I have read and agree to this Customer Information Accuracy Declaration.";

export const PRIVACY_TEXT =
  "I acknowledge that Banana Nut Burger will store my registration information and signed documents privately to manage my customer record and bookings, and that I may request corrections by contacting the business.";
export const MARKETING_TEXT =
  "I agree to receive occasional offers and news from Banana Nut Burger by WhatsApp or email. (Optional)";

const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

export function buildDocument({ ref, customer, data, consents, signerName, signedAtISO, docHash, signatureDataUrl }) {
  const row = (k, v) => `<tr><th>${esc(k)}</th><td>${esc(v || "-")}</td></tr>`;
  const consentRows = consents.map((c) => `<li>${esc(c.purpose)}: <b>${c.granted ? "AGREED" : "not granted"}</b> (${esc(c.textVersion)})</li>`).join("");
  return `<!doctype html><html><head><meta charset="utf-8"><title>Registration ${esc(ref)}</title>
<style>body{font-family:system-ui,sans-serif;max-width:720px;margin:24px auto;padding:0 16px;color:#0a2533}table{border-collapse:collapse;width:100%}th,td{border:1px solid #ccc;padding:8px;text-align:left;vertical-align:top}th{width:220px;background:#fff8e6}img.sig{max-width:320px;border:1px solid #ccc;border-radius:8px}.mut{color:#666;font-size:13px}</style></head><body>
<h1>Banana Nut Burgers Dive Shop — Customer Registration</h1>
<p class="mut">Registration reference: <b>${esc(ref)}</b> · Form version: ${esc(FORM_VERSION)} · Document SHA-256: ${esc(docHash)}</p>
<h2>Customer information</h2><table>
${row("First name", customer.firstName)}${row("Last name", customer.lastName)}${row("Preferred name", customer.preferredName)}
${row("Phone", customer.phone)}${row("Email", customer.email)}
${row("Certification level", data.cert)}${row("Logged dives", data.loggedDives)}${row("Date of last dive", data.lastDive)}
${row("Emergency contact", data.emergencyName)}${row("Emergency phone", data.emergencyPhone)}${row("Notes", data.notes)}
</table>
<h2>${esc(DECLARATION_TITLE)}</h2><p>${esc(DECLARATION_TEXT)}</p>
<h2>Acknowledgements &amp; consent</h2><ul>${consentRows}</ul>
<h2>Electronic signature</h2>
<p>Signed by: <b>${esc(signerName)}</b><br>Signed at (UTC): ${esc(signedAtISO)}</p>
${signatureDataUrl ? `<img class="sig" alt="Signature" src="${signatureDataUrl}">` : ""}
<p class="mut">This document was generated by the Banana Nut Burger registration system. The signature, consent records, and audit trail are stored with this registration reference.</p>
</body></html>`;
}
